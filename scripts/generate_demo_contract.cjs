const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
function generate(c) {
  const scenes = ['boot','home','ready','focus','encouragement','complete','growth','summary'];
  const poses = ['idle','ready','focus','support','complete','growth'];
  if (c.version !== 1 || JSON.stringify(c.scenes) !== JSON.stringify(scenes) ||
      JSON.stringify(c.actions) !== JSON.stringify(['next','restart','startFocus'])) throw Error('Invalid demo protocol');
  if (Object.keys(c.palette).length !== 8 || ['background','primary','ready','paused','complete','support','text','muted'].some(k=>!(k in c.palette)) || poses.some(p => !c.poses[p]) || Object.keys(c.poses).length !== 6) throw Error('Invalid visual tokens');
  for (const color of Object.values(c.palette)) if (!/^#[0-9a-f]{6}$/i.test(color)) throw Error('Invalid color');
  if (new Set(Object.values(c.poses).map(JSON.stringify)).size !== 6) throw Error('Poses must differ');
  if (JSON.stringify(c.scenePoses)!==JSON.stringify(['idle','idle','ready','focus','support','complete','growth','idle'])) throw Error('Invalid scene pose mapping');
  if (c.animation.stepMs !== 300 || c.animation.durationMs !== 900 || !c.animation.focusStatic) throw Error('Invalid animation');
  for (const p of poses) for (const m of c.poses[p]) {
    if (m.length !== 6 || !['circle','line'].includes(m[0]) || m.slice(1,5).some(v => !Number.isInteger(v))) throw Error('Invalid mark');
    const [,x,y,a,b,ink] = m;
    if (!(ink === 'accent' || ink in c.palette) || !(c.poseAccents[p] in c.palette)) throw Error('Invalid ink');
    if (m[0] === 'circle' ? a < 1 || x-a < 0 || y-a < 0 || x+a > 63 || y+a > 63 : [x,y,a,b].some(v => v < 0 || v > 63)) throw Error('Mark out of bounds');
  }
  for (const k of ['serviceUuid','commandUuid','stateUuid']) if (!/^7df2[0-9a-f-]{32}$/i.test(c[k])) throw Error('Use isolated Demo UUIDs');
  if (c.names.orbit !== 'Nudge Orbit Demo' || c.names.station !== 'Nudge Station Demo') throw Error('Invalid names');
  const rgb565 = hex => { const n=parseInt(hex.slice(1),16);return ((n>>19)<<11)|(((n>>10)&63)<<5)|((n>>3)&31); };
  let h = '// Generated by scripts/generate_demo_contract.cjs; source: shared/demo_contract.json\n#pragma once\n#include <cstdint>\n#include <cstddef>\nnamespace demo {\nnamespace color {\n';
  for (const [k,v] of Object.entries(c.palette)) h += `inline constexpr std::uint16_t ${k} = 0x${rgb565(v).toString(16)};\n`;
  h += '}\nnamespace contract {\n';
  for (const [key,name] of [['serviceUuid','kServiceUuid'],['commandUuid','kCommandUuid'],['stateUuid','kStateUuid']]) h += `inline constexpr char ${name}[] = "${c[key]}";\n`;
  h += `inline constexpr const char* kDeviceNames[] = {"${c.names.orbit}","${c.names.station}"};\n`;
  h += `inline constexpr const char* kScenes[] = {${scenes.map(s=>JSON.stringify(s)).join(',')}};\n`;
  h += `enum class Pose : std::uint8_t { ${poses.join(',')} };\nstruct Mark { char kind; int x,y,a,b; std::uint16_t ink; };\n`;
  for (const p of poses) h += `inline constexpr Mark ${p}Marks[] = {\n${c.poses[p].map(([op,x,y,a,b,ink])=>`  {'${op==='circle'?'c':'l'}',${x},${y},${a},${b},color::${ink==='accent'?c.poseAccents[p]:ink}},`).join('\n')}\n};\n`;
  h += 'struct Asset { const Mark* marks; std::size_t size; };\ninline Asset asset(Pose pose) { switch(pose) {\n';
  for (const p of poses) h += `case Pose::${p}: return {${p}Marks,sizeof(${p}Marks)/sizeof(Mark)};\n`;
  h += '} return {nullptr,0}; }\n';
  h += `inline constexpr Pose kScenePoses[] = {${c.scenePoses.map(p=>'Pose::'+p).join(',')}};\n}\n}\n`;
  let d = '// Generated from shared/demo_contract.json. Do not edit.\n// dart format off\n';
  for (const k of ['serviceUuid','commandUuid','stateUuid']) d += `const demo${k[0].toUpperCase()+k.slice(1)} = '${c[k]}';\n`;
  d += `const demoDeviceNames = <String,String>{'orbit':'${c.names.orbit}','station':'${c.names.station}'};\n`;
  d += `const demoActions = <String>${JSON.stringify(c.actions)};\nconst demoSceneNames = <String>${JSON.stringify(scenes)};\nconst demoScenePoses = <String>${JSON.stringify(c.scenePoses)};\n`;
  d += `const demoPalette = <String,int>{${Object.entries(c.palette).map(([k,v])=>`'${k}':0xff${v.slice(1)}`).join(',')}};\n`;
  d += 'class DemoMark { const DemoMark(this.kind,this.x,this.y,this.a,this.b,this.ink); final String kind,ink; final int x,y,a,b; }\nconst demoPoseMarks = <String,List<DemoMark>>{\n';
  for (const p of poses) d += `'${p}':[${c.poses[p].map(([op,x,y,a,b,ink])=>`DemoMark('${op}',${x},${y},${a},${b},'${ink==='accent'?c.poseAccents[p]:ink}')`).join(',')}],\n`;
  d += '};\n';
  let k='// Generated from shared/demo_contract.json. Do not edit.\npackage com.example.nudge\n\nobject DemoBleSpec {\n';
  for(const key of ['serviceUuid','commandUuid','stateUuid'])k+=`    const val ${key} = "${c[key]}"\n`;
  k+=`    val names = mapOf("orbit" to "${c.names.orbit}", "station" to "${c.names.station}")\n`;
  k+=`    val actions = setOf(${c.actions.map(JSON.stringify).join(', ')})\n}\n`;
  return {header:h,dart:d,kotlin:k};
}
module.exports={generate};
if (require.main === module) {
  const out = generate(JSON.parse(fs.readFileSync(path.join(root,'shared/demo_contract.json'),'utf8')));
  for (const [name,body] of [['firmware/nudge_competition_demo/include/demo/generated_contract.h',out.header],['lib/demo/generated_demo_contract.dart',out.dart],['android/app/src/main/kotlin/com/example/nudge/DemoBleSpec.kt',out.kotlin]]) {
    const target=path.join(root,name);
    if (process.argv.includes('--check')) { if (!fs.existsSync(target) || fs.readFileSync(target,'utf8')!==body) throw Error(`Outdated ${name}`); }
    else {fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,body);}
  }
  process.stdout.write('Demo protocol/visual contract verified\n');
}
