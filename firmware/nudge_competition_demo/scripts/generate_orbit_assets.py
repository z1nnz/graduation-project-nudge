"""Compile existing App art and a small TC label subset into bounded RGB565 runs.

No runtime PNG decoder, font library, filesystem, network, or heap allocation.
Run with the workspace Python runtime (Pillow), then commit the generated header.
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[3]
OUTPUT = Path(__file__).resolve().parents[1] / 'include/demo/orbit_assets.h'

def rgb565(rgb):
    r, g, b = rgb
    return (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)

def pixel_ink(pixel):
    r, g, b, alpha = pixel
    if alpha < 96:
        return None
    # Quantization bounds generated flash size while preserving the art.
    return rgb565(tuple((c // 16) * 16 for c in (r, g, b)))

def runs(image):
    image = image.convert('RGBA')
    data = []
    for y in range(image.height):
        x = 0
        while x < image.width:
            ink = pixel_ink(image.getpixel((x, y)))
            if ink is None:
                x += 1
                continue
            start = x
            x += 1
            while x < image.width:
                if pixel_ink(image.getpixel((x, y))) != ink:
                    break
                x += 1
            data.append((start, y, x-start, ink))
    return data

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--font', required=True, help='NotoSansCJKtc-Regular.otf')
    args = parser.parse_args()
    source = ROOT / 'assets/avatar/characters/character_0.png'
    art = Image.open(source).convert('RGBA')
    art = art.crop(art.getbbox())
    images = {}
    for name, height in [('hero', 126), ('focusHero', 68)]:
        width = round(art.width * height / art.height)
        images[name] = art.resize((width, height), Image.Resampling.LANCZOS)
    font = ImageFont.truetype(args.font, 16)
    labels = {
        'today': '今日小目標', 'focus': '專注中', 'complete': '完成一小步',
        'ready': '準備出發', 'support': '一起前進', 'growth': '成長旅程',
        'summary': '今日足跡', 'focusHint': '專注', 'companion': '星辰學徒',
    }
    for name, text in labels.items():
        w = round(font.getlength(text))
        bounds = font.getbbox(text)
        im = Image.new('RGBA', (w, bounds[3]-bounds[1]))
        ImageDraw.Draw(im).text((0, -bounds[1]), text, font=font, fill=(226, 218, 255, 255))
        images[name] = im
    lines = [
        '// Generated by scripts/generate_orbit_assets.py; do not edit.',
        '// Art: assets/avatar/characters/character_0.png (App 星辰學徒).',
        '// Labels: Noto Sans CJK TC (SIL OFL); only fixed demo labels are compiled.',
        '#pragma once', '#include <cstdint>', '#include <cstddef>',
        'namespace demo { namespace orbit_assets {',
        'struct Run { std::uint8_t x, y, width; std::uint16_t ink; };',
        'struct Image { const Run* runs; std::size_t count; int width, height; };',
    ]
    for name, image in images.items():
        values = runs(image)
        lines.append(f'inline constexpr Run {name}Runs[] = {{')
        lines.extend(f'{{{x},{y},{w},0x{ink:04x}}},' for x,y,w,ink in values)
        lines.append('};')
        lines.append(f'inline constexpr Image {name} = {{{name}Runs, sizeof({name}Runs)/sizeof(Run), {image.width}, {image.height}}};')
    lines.append('} } // namespace demo::orbit_assets')
    OUTPUT.write_text('\n'.join(lines)+'\n')
    print(f'generated {OUTPUT.name}: {sum(len(runs(im)) for im in images.values())} runs')

if __name__ == '__main__':
    main()
