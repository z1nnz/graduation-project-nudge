  @override
  Future<ByteData> load(String key) async {
    if (key.startsWith('AssetManifest') || key.startsWith('FontManifest')) {
      return rootBundle.load(key);
    }
    final f = File(key);
    final bytes = f.existsSync() ? f.readAsBytesSync() : _blank;
    return ByteData.sublistView(bytes);
  }
}
